import json
import re
from collections.abc import Mapping
from os import environ

from dotenv import load_dotenv
from microsoft_agents.activity import Activity, load_configuration_from_env
from microsoft_agents.authentication.msal import MsalConnectionManager
from microsoft_agents.hosting.aiohttp import CloudAdapter
from microsoft_agents.hosting.core import AgentApplication, MemoryStorage, TurnContext, TurnState
from microsoft_agents.hosting.msteams import TeamsAgentExtension


AI_LABEL = "label"
SENSITIVITY_LABEL = "sensitivity"
FEEDBACK_BUTTONS = "feedback"
CITATION = "citation"


def _message(
    text: str,
    entities: list[dict[str, object]],
    channel_data: dict[str, object] | None = None,
) -> Activity:
    return Activity(
        type="message",
        text=text,
        entities=entities,
        channel_data=channel_data,
    )


def _schema_message(**values: object) -> dict[str, object]:
    return {
        "type": "https://schema.org/Message",
        "@type": "Message",
        "@context": "https://schema.org",
        "@id": "",
        **values,
    }


async def _send_invoke_response(context: TurnContext, body: dict[str, object]) -> None:
    await context.send_activity(
        Activity(
            type="invokeResponse",
            reply_to_id=context.activity.id,
            value={"status": 200, "body": body},
        )
    )


def create_agent(dependencies: Mapping[str, object] | None = None) -> AgentApplication:
    load_dotenv()
    config = load_configuration_from_env(environ)
    deps = dependencies or {}

    connection_manager = deps.get("connection_manager")
    if connection_manager is None:
        connection_manager = MsalConnectionManager(**config)

    adapter = deps.get("adapter")
    if adapter is None:
        adapter = CloudAdapter(connection_manager=connection_manager)

    app = AgentApplication[TurnState](
        storage=MemoryStorage(),
        adapter=adapter,
        connection_manager=connection_manager,
        **config,
    )
    TeamsAgentExtension(app)

    @app.activity("message")
    async def on_message(context: TurnContext, _state: TurnState) -> None:
        text = context.activity.text or ""

        if re.search(AI_LABEL, text, re.IGNORECASE):
            await context.send_activity(
                _message(
                    "Hi, this message is generated by AI",
                    [_schema_message(additionalType=["AIGeneratedContent"])],
                )
            )
        elif re.search(SENSITIVITY_LABEL, text, re.IGNORECASE):
            await context.send_activity(
                _message(
                    "This is an example of a sensitivity label that help users identify the confidentiality of a message",
                    [
                        _schema_message(
                            usageInfo={
                                "@type": "CreativeWork",
                                "name": "Confidential \\ Contoso FTE",
                                "description": "Please be mindful of sharing outside of your team",
                            }
                        )
                    ],
                )
            )
        elif re.search(FEEDBACK_BUTTONS, text, re.IGNORECASE):
            await context.send_activity(
                _message(
                    "This is an example of a feedback button - this helps to provide feedback for a message",
                    [],
                    channel_data={"feedbackLoop": {"type": "custom"}},
                )
            )
        elif re.search(CITATION, text, re.IGNORECASE):
            card = {
                "type": "AdaptiveCard",
                "version": "1.6",
                "body": [{"type": "TextBlock", "text": "Adaptive Card text"}],
            }
            citation = {
                "@type": "Claim",
                "position": 1,
                "appearance": {
                    "@type": "DigitalDocument",
                    "name": "AI messages agent",
                    "url": "https://example.com/claim-1",
                    "abstract": "Excerpt description",
                    "text": json.dumps(card, separators=(",", ":")),
                    "encodingFormat": "application/vnd.microsoft.card.adaptive",
                    "keywords": ["keyword 1", "keyword 2", "keyword 3"],
                    "image": {"@type": "ImageObject", "name": "Microsoft Word"},
                },
            }
            await context.send_activity(
                _message(
                    "Hey I'm a friendly AI agent. This message is generated through AI [1]",
                    [_schema_message(citation=[citation])],
                )
            )
        else:
            await context.send_activity(
                "Welcome to the AI agent! Try sending messages with keywords like "
                "'label', 'sensitivity', 'feedback', or 'citation' to see different AI features."
            )

    @app.invoke("message/submitAction")
    async def handle_feedback(context: TurnContext, _state: TurnState) -> None:
        value = context.activity.value
        if not isinstance(value, Mapping):
            raise ValueError("Feedback invoke value must be an object.")
        action_value = value.get("actionValue")
        if not isinstance(action_value, Mapping):
            raise ValueError("Feedback invoke actionValue must be an object.")

        reaction = action_value.get("reaction", "No reaction")
        raw_feedback = action_value.get("feedback", "{}")
        if isinstance(raw_feedback, str):
            feedback = json.loads(raw_feedback)
        elif isinstance(raw_feedback, Mapping):
            feedback = raw_feedback
        else:
            raise ValueError("Feedback value must be a JSON object or JSON string.")
        if not isinstance(feedback, Mapping):
            raise ValueError("Feedback JSON must contain an object.")

        feedback_text = feedback.get("feedbackText") or "No feedback was provided."
        await context.send_activity(
            f"Provided reaction: {reaction}<br> Feedback: {feedback_text}"
        )
        await _send_invoke_response(context, {})

    @app.invoke("message/fetchTask")
    async def handle_feedback_fetch_task(
        context: TurnContext, _state: TurnState
    ) -> None:
        card = {
            "type": "AdaptiveCard",
            "version": "1.4",
            "body": [
                {"type": "TextBlock", "text": "Tell us more about your feedback:"},
                {
                    "type": "Input.Text",
                    "id": "feedbackText",
                    "placeholder": "Enter your feedback here...",
                    "isMultiline": True,
                },
            ],
            "actions": [{"type": "Action.Submit", "title": "Submit"}],
        }
        await _send_invoke_response(
            context,
            {
                "task": {
                    "type": "continue",
                    "value": {
                        "title": "Feedback",
                        "card": {
                            "contentType": "application/vnd.microsoft.card.adaptive",
                            "content": card,
                        },
                    },
                }
            },
        )

    return app
