"""Agents SDK application and Teams AI message handlers."""

import json
import logging
from os import environ

from dotenv import load_dotenv
from microsoft_agents.activity import Activity, load_configuration_from_env
from microsoft_agents.authentication.msal import MsalConnectionManager
from microsoft_agents.hosting.aiohttp import CloudAdapter
from microsoft_agents.hosting.core import (
    AgentApplication,
    MemoryStorage,
    TurnContext,
    TurnState,
)
from microsoft_agents.hosting.msteams import TeamsAgentExtension

logger = logging.getLogger(__name__)

HELP_TEXT = (
    "Welcome to the AI agent! Try sending messages with keywords like "
    "'label', 'sensitivity', 'feedback', or 'citation' to see different AI features."
)
AI_LABEL_TEXT = "Hi, this message is generated by AI"
SENSITIVITY_TEXT = (
    "This is an example of a sensitivity label that help users identify "
    "the confidentiality of a message"
)
FEEDBACK_TEXT = (
    "This is an example of a feedback button - this helps to provide "
    "feedback for a message"
)
CITATION_TEXT = "Hey I'm a friendly AI agent. This message is generated through AI [1]"


def _message_with_entity(text: str, entity: dict) -> Activity:
    return Activity(
        type="message",
        text=text,
        entities=[
            {
                "type": "https://schema.org/Message",
                "@type": "Message",
                "@context": "https://schema.org",
                "@id": "",
                **entity,
            }
        ],
    )


def _feedback_fetch_response() -> Activity:
    card = {
        "type": "AdaptiveCard",
        "version": "1.4",
        "body": [
            {"type": "TextBlock", "text": "Tell us more about your feedback:"},
            {
                "type": "Input.Text",
                "id": "feedbackText",
                "placeholder": "Enter your feedback here...",
                "isMultiline": True,
            },
        ],
        "actions": [{"type": "Action.Submit", "title": "Submit"}],
    }
    return Activity(
        type="invokeResponse",
        value={
            "status": 200,
            "body": {
                "task": {
                    "type": "continue",
                    "value": {
                        "title": "Feedback",
                        "card": {
                            "contentType": "application/vnd.microsoft.card.adaptive",
                            "content": card,
                        },
                    },
                }
            },
        },
    )


def _invoke_acknowledgement() -> Activity:
    return Activity(type="invokeResponse", value={"status": 200})


async def _handle_feedback_submit(context: TurnContext, _state: TurnState) -> None:
    value = context.activity.value
    action_value = value.get("actionValue")
    if not isinstance(action_value, dict):
        raise ValueError("Feedback invoke is missing its actionValue object.")
    reaction = action_value.get("reaction") or "No reaction"
    raw_feedback = action_value.get("feedback")
    if raw_feedback is None:
        feedback_text = "No feedback was provided."
    else:
        feedback = json.loads(raw_feedback) if isinstance(raw_feedback, str) else raw_feedback
        if not isinstance(feedback, dict):
            raise ValueError("Feedback invoke feedback must be a JSON object.")
        feedback_text = feedback.get("feedbackText") or "No feedback was provided."
    await context.send_activity(_invoke_acknowledgement())
    await context.send_activity(
        f"Provided reaction: {reaction}<br> Feedback: {feedback_text}"
    )


async def _handle_feedback_fetch(context: TurnContext, _state: TurnState) -> None:
    await context.send_activity(_feedback_fetch_response())


def create_agent(dependencies: dict | None = None) -> AgentApplication:
    """Build an isolated Agents SDK app; injected transports support offline checks."""
    load_dotenv()
    options = dependencies or {}
    configuration = load_configuration_from_env(environ)
    connection_manager = options.get("connection_manager")
    if connection_manager is None:
        connection_manager = MsalConnectionManager(**configuration)
    adapter = options.get("adapter")
    if adapter is None:
        adapter = CloudAdapter(connection_manager=connection_manager)

    app = AgentApplication(
        storage=MemoryStorage(),
        adapter=adapter,
        connection_manager=connection_manager,
        **configuration,
    )
    TeamsAgentExtension(app)

    async def add_ai_label(context: TurnContext, _state: TurnState) -> None:
        await context.send_activity(
            _message_with_entity(
                AI_LABEL_TEXT,
                {"additionalType": ["AIGeneratedContent"]},
            )
        )

    async def add_sensitivity_label(context: TurnContext, _state: TurnState) -> None:
        await context.send_activity(
            _message_with_entity(
                SENSITIVITY_TEXT,
                {
                    "usageInfo": {
                        "@type": "CreativeWork",
                        "name": "Confidential \\ Contoso FTE",
                        "description": (
                            "Please be mindful of sharing outside of your team"
                        ),
                    }
                },
            )
        )

    async def add_feedback_buttons(context: TurnContext, _state: TurnState) -> None:
        await context.send_activity(
            Activity(
                type="message",
                text=FEEDBACK_TEXT,
                channel_data={"feedbackLoop": {"type": "custom"}},
            )
        )

    async def add_citations(context: TurnContext, _state: TurnState) -> None:
        card = {
            "type": "AdaptiveCard",
            "version": "1.6",
            "body": [{"type": "TextBlock", "text": "Adaptive Card text"}],
        }
        appearance = {
            "@type": "DigitalDocument",
            "name": "AI messages agent",
            "url": "https://example.com/claim-1",
            "abstract": "Excerpt description",
            "text": json.dumps(card, separators=(",", ":")),
            "encodingFormat": "application/vnd.microsoft.card.adaptive",
            "keywords": ["keyword 1", "keyword 2", "keyword 3"],
            "image": {"@type": "ImageObject", "name": "Microsoft Word"},
        }
        await context.send_activity(
            _message_with_entity(
                CITATION_TEXT,
                {
                    "citation": [
                        {"@type": "Claim", "position": 1, "appearance": appearance}
                    ]
                },
            )
        )

    @app.activity("message")
    async def handle_message(context: TurnContext, state: TurnState) -> None:
        message_text = (context.activity.text or "").lower()
        if "label" in message_text:
            await add_ai_label(context, state)
        elif "sensitivity" in message_text:
            await add_sensitivity_label(context, state)
        elif "feedback" in message_text:
            await add_feedback_buttons(context, state)
        elif "citation" in message_text:
            await add_citations(context, state)
        else:
            await context.send_activity(HELP_TEXT)

    @app.invoke("message/submitAction")
    async def on_feedback_submit(context: TurnContext, state: TurnState) -> None:
        await _handle_feedback_submit(context, state)

    @app.invoke("message/fetchTask")
    async def on_feedback_fetch(context: TurnContext, state: TurnState) -> None:
        await _handle_feedback_fetch(context, state)

    return app
