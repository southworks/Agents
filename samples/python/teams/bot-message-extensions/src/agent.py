import logging
import re
from collections.abc import Mapping
from os import environ
from typing import Any

from dotenv import load_dotenv
from microsoft_agents.activity import Activity, load_configuration_from_env
from microsoft_agents.authentication.msal import MsalConnectionManager
from microsoft_agents.hosting.aiohttp import CloudAdapter
from microsoft_agents.hosting.core import AgentApplication, MemoryStorage, TurnState
from microsoft_agents.hosting.msteams import TeamsAgentExtension

from src.wikipedia import search_wikipedia

logger = logging.getLogger(__name__)
SEARCH_COMMAND_ID = "wikipediaSearch"


def _read_field(value: Any, field: str, default: Any = None) -> Any:
    if isinstance(value, Mapping):
        return value.get(field, default)
    return getattr(value, field, default)


def _query_text(value: Any) -> str:
    parameters = _read_field(value, "parameters", None) or []
    if not parameters:
        return ""
    first_parameter = parameters[0]
    return str(_read_field(first_parameter, "value", "") or "")


def _clean_snippet(snippet: str) -> str:
    return re.sub(r"<[^>]+>", "", snippet)


def _wikipedia_card(result: Mapping[str, Any]) -> dict[str, Any]:
    title = str(result.get("title") or "No Title")
    snippet = _clean_snippet(str(result.get("snippet") or ""))
    article_title = title.replace(" ", "_")
    return {
        "type": "AdaptiveCard",
        "version": "1.4",
        "body": [
            {"type": "TextBlock", "text": title, "weight": "Bolder", "size": "Large"},
            {
                "type": "TextBlock",
                "text": snippet,
                "wrap": True,
                "isSubtle": True,
            },
        ],
        "actions": [
            {
                "type": "Action.OpenUrl",
                "title": "Read on Wikipedia",
                "url": f"https://en.wikipedia.org/wiki/{article_title}",
            }
        ],
    }


def _search_attachment(result: Mapping[str, Any]) -> dict[str, Any]:
    title = str(result.get("title") or "No Title")
    snippet = _clean_snippet(str(result.get("snippet") or ""))
    return {
        "contentType": "application/vnd.microsoft.card.adaptive",
        "content": _wikipedia_card(result),
        "preview": {
            "contentType": "application/vnd.microsoft.card.thumbnail",
            "content": {"title": title, "text": snippet},
        },
    }


def _link_preview(url: str) -> dict[str, Any]:
    return {
        "type": "AdaptiveCard",
        "version": "1.4",
        "body": [
            {"type": "TextBlock", "text": "Link Preview", "weight": "Bolder", "size": "Medium"},
            {
                "type": "TextBlock",
                "text": f"URL: {url}",
                "isSubtle": True,
                "wrap": True,
            },
            {
                "type": "TextBlock",
                "text": "This is a preview of the linked content generated by the message extension.",
                "wrap": True,
                "size": "Small",
            },
        ],
    }


def _extension_result(attachments: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "composeExtension": {
            "type": "result",
            "attachmentLayout": "list",
            "attachments": attachments,
        }
    }


def _no_results(query: str) -> dict[str, Any]:
    return {
        "composeExtension": {
            "type": "message",
            "text": f"No results found for '{query}'",
        }
    }


def create_agent(dependencies: Mapping[str, Any] | None = None) -> AgentApplication:
    load_dotenv()
    supplied = dependencies or {}
    configuration = load_configuration_from_env(environ)
    connection_manager = supplied.get("connection_manager")
    if connection_manager is None:
        connection_manager = MsalConnectionManager(**configuration)

    adapter = supplied.get("adapter")
    if adapter is None:
        adapter = CloudAdapter(connection_manager=connection_manager)

    search = supplied.get("search_wikipedia", search_wikipedia)
    if not callable(search):
        raise TypeError("search_wikipedia dependency must be callable")

    app = AgentApplication[TurnState](
        storage=MemoryStorage(),
        adapter=adapter,
        connection_manager=connection_manager,
    )
    teams = TeamsAgentExtension(app)

    @teams.message_extensions.query(SEARCH_COMMAND_ID)
    async def handle_query(context, _state, payload):
        query = _query_text(payload)
        if payload.command_id != SEARCH_COMMAND_ID:
            return _no_results(query)

        results = await search(query)
        attachments = [
            _search_attachment(result)
            for result in results
        ]
        if not attachments:
            return _no_results(query)
        return _extension_result(attachments)

    @teams.message_extensions.query_link
    async def handle_link(_context, _state, payload):
        url = str(_read_field(payload, "url", "") or "")
        attachment = {
            "contentType": "application/vnd.microsoft.card.adaptive",
            "content": _link_preview(url),
        }
        return _extension_result([attachment])

    @app.activity("message")
    async def handle_message(context, _state):
        text = context.activity.text or ""
        if "help" in text.lower():
            await context.send_activity(
                "Hi! I'm the Wikipedia Search agent!\n\n"
                "Use me in the compose area to search for Wikipedia articles.\n"
            )
        else:
            await context.send_activity(
                f"You said: {context.activity.text}\n\nType 'help' to learn more."
            )

    @app.invoke()
    async def handle_unknown_invoke(context, _state):
        if context.activity.name != "composeExtension/query":
            return
        query = _query_text(context.activity.value)
        response = Activity(
            type="invokeResponse",
            value={"status": 200, "body": _no_results(query)},
        )
        await context.send_activity(response)

    return app
