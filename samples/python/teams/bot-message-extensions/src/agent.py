import re
from os import environ
from typing import Any
from urllib.parse import quote

from dotenv import load_dotenv
from microsoft_agents.activity import Activity
from microsoft_agents.authentication.msal import MsalConnectionManager
from microsoft_agents.hosting.aiohttp import CloudAdapter
from microsoft_agents.hosting.core import AgentApplication, MemoryStorage
from microsoft_agents.hosting.msteams import TeamsAgentExtension

from .search import search_wikipedia as default_search_wikipedia


def _article_attachment(article: dict[str, Any]) -> dict[str, Any]:
    title = article.get("title") or "No Title"
    snippet = re.sub(r"<[^>]+>", "", article.get("snippet") or "")
    wikipedia_url = (
        "https://en.wikipedia.org/wiki/"
        + quote(title.replace(" ", "_"), safe="_()")
    )
    return {
        "contentType": "application/vnd.microsoft.card.adaptive",
        "content": {
            "type": "AdaptiveCard",
            "version": "1.5",
            "body": [
                {"type": "TextBlock", "text": title, "weight": "Bolder", "size": "Large"},
                {"type": "TextBlock", "text": snippet, "wrap": True, "isSubtle": True},
                {
                    "type": "ActionSet",
                    "actions": [
                        {"type": "Action.OpenUrl", "title": "Read on Wikipedia", "url": wikipedia_url}
                    ],
                },
            ],
        },
        "preview": {
            "contentType": "application/vnd.microsoft.card.thumbnail",
            "content": {"title": title, "text": snippet},
        },
    }


def _no_results(query: str) -> dict[str, Any]:
    return {"composeExtension": {"type": "message", "text": f"No results found for '{query}'"}}


def _link_preview(url: str) -> dict[str, Any]:
    attachment = {
        "contentType": "application/vnd.microsoft.card.adaptive",
        "content": {
            "type": "AdaptiveCard",
            "version": "1.5",
            "body": [
                {"type": "TextBlock", "text": "Link Preview", "weight": "Bolder", "size": "Medium"},
                {"type": "TextBlock", "text": f"URL: {url}", "isSubtle": True, "wrap": True},
                {
                    "type": "TextBlock",
                    "text": "This is a preview of the linked content generated by the message extension.",
                    "wrap": True,
                    "size": "Small",
                },
            ],
        },
    }
    return {
        "composeExtension": {
            "type": "result",
            "attachmentLayout": "list",
            "attachments": [attachment],
        }
    }


def create_agent(dependencies: dict[str, Any] | None = None) -> AgentApplication:
    deps = dependencies or {}
    connection_manager = deps.get("connection_manager")
    if connection_manager is None:
        load_dotenv()
        connection_manager = MsalConnectionManager(**load_configuration())
    adapter = deps.get("adapter")
    if adapter is None:
        adapter = CloudAdapter(connection_manager=connection_manager)

    app = AgentApplication(
        storage=MemoryStorage(),
        adapter=adapter,
        connection_manager=connection_manager,
    )
    teams = TeamsAgentExtension(app)
    search = deps.get("search_wikipedia", default_search_wikipedia)

    @teams.message_extensions.query("wikipediaSearch")
    async def handle_query(_context, _state, payload):
        parameters = payload.parameters or []
        query = str(parameters[0].value) if parameters else ""
        articles = await search(query)
        if not articles:
            return _no_results(query)
        return {
            "composeExtension": {
                "type": "result",
                "attachmentLayout": "list",
                "attachments": [_article_attachment(article) for article in articles[:8]],
            }
        }

    @teams.message_extensions.query_link()
    async def handle_query_link(_context, _state, payload):
        return _link_preview(payload.url)

    @app.invoke()
    async def handle_unknown_query(context, _state):
        if context.activity.name != "composeExtension/query":
            return
        value = context.activity.value or {}
        parameters = value.get("parameters") or []
        query = str(parameters[0].get("value", "")) if parameters else ""
        await context.send_activity(
            Activity(
                type="invokeResponse",
                value={"status": 200, "body": _no_results(query)},
            )
        )

    @app.activity("message")
    async def handle_message(context, _state):
        text = context.activity.text or ""
        if "help" in text.lower():
            await context.send_activity(
                "Hi! I'm the Wikipedia Search Agent!\n\n"
                "Use me in the compose area to search for Wikipedia articles\n"
            )
        else:
            await context.send_activity(
                f"You said: {text}\n\nType 'help' to learn more."
            )

    return app


def load_configuration():
    from microsoft_agents.activity import load_configuration_from_env

    return load_configuration_from_env(environ)
