"""Convert trusted pip wheel-resolution reports into requirements hash locks."""

import re
from urllib.parse import unquote, urlsplit

from packaging.utils import canonicalize_name, parse_wheel_filename
from packaging.version import Version


def lock_from_report(report, selected_packages):
    if not isinstance(report, dict) or report.get("version") != "1":
        raise ValueError("Unsupported pip resolution report version")
    if report.get("pip_version") != "26.1.1":
        raise ValueError("Resolver report must be produced by pinned pip 26.1.1")
    installs = report.get("install")
    if not isinstance(installs, list) or not installs:
        raise ValueError("Resolver report contains no distributions")
    resolved = {}
    for item in installs:
        if item.get("is_direct") or item.get("is_yanked"):
            raise ValueError("Direct or yanked distributions are forbidden")
        metadata = item["metadata"]
        name = canonicalize_name(metadata["name"])
        version = Version(metadata["version"])
        if name in resolved:
            raise ValueError(f"Duplicate resolved distribution: {name}")
        download = item["download_info"]
        url = urlsplit(download["url"])
        if url.scheme != "https" or url.hostname != "files.pythonhosted.org" or url.port:
            raise ValueError(f"Untrusted distribution source: {name}")
        if url.username or url.password or url.query or url.fragment:
            raise ValueError(f"Unsupported distribution URL: {name}")
        filename = unquote(url.path.rsplit("/", 1)[-1])
        wheel_name, wheel_version, _, _ = parse_wheel_filename(filename)
        if wheel_name != name or wheel_version != version:
            raise ValueError(f"Wheel identity differs from resolver metadata: {name}")
        digest = download.get("archive_info", {}).get("hashes", {}).get("sha256")
        if not isinstance(digest, str) or not re.fullmatch(r"[a-f0-9]{64}", digest):
            raise ValueError(f"Missing valid wheel SHA-256: {name}")
        resolved[name] = (str(version), digest)

    for name, expected in selected_packages.items():
        if name not in resolved or resolved[name][0] != expected:
            raise ValueError(f"Resolved SDK differs from frozen selection: {name}")
    lines = ["# Generated by trusted Teams sample synchronization tooling."]
    lines.extend(
        f"{name}=={version} --hash=sha256:{digest}"
        for name, (version, digest) in sorted(resolved.items())
    )
    return "\n".join(lines) + "\n"
