"""AI message metadata and feedback through the real SDK route pipeline."""

import json
import unittest

from harness import dispatch, invoke_response, sample_application


class AiMessageContracts(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        self.app = sample_application()

    async def test_label_precedes_other_keywords(self):
        sent = await dispatch(self.app, {"text": "sensitivity label feedback citation"})
        self.assertEqual(sent[0]["text"], "Hi, this message is generated by AI")
        self.assertIn("AIGeneratedContent", sent[0]["entities"][0]["additionalType"])

    async def test_sensitivity_and_custom_feedback_metadata(self):
        sensitivity = await dispatch(self.app, {"text": "sensitivity"})
        self.assertEqual(sensitivity[0]["entities"][0]["usageInfo"]["name"], "Confidential \\ Contoso FTE")
        feedback = await dispatch(self.app, {"text": "feedback"})
        # Python upstream includes a custom feedback dialog; preserve that behavior.
        self.assertEqual(feedback[0]["channelData"]["feedbackLoop"]["type"], "custom")

    async def test_complete_citation(self):
        sent = await dispatch(self.app, {"text": "citation"})
        claim = sent[0]["entities"][0]["citation"][0]
        self.assertEqual(claim["position"], 1)
        appearance = claim["appearance"]
        self.assertEqual(appearance["url"], "https://example.com/claim-1")
        self.assertEqual(appearance["image"]["name"], "Microsoft Word")
        self.assertEqual(appearance["encodingFormat"], "application/vnd.microsoft.card.adaptive")
        self.assertEqual(appearance["keywords"], ["keyword 1", "keyword 2", "keyword 3"])
        self.assertEqual(json.loads(appearance["text"])["body"][0]["text"], "Adaptive Card text")
        self.assertIn("[1]", sent[0]["text"])

    async def test_feedback_submission_preserves_reaction_and_text(self):
        sent = await dispatch(self.app, {
            "type": "invoke", "name": "message/submitAction",
            "value": {"actionName": "feedback", "actionValue": {
                "reaction": "like", "feedback": '{"feedbackText":"Useful"}',
            }},
        })
        self.assertIn("Provided reaction: like<br> Feedback: Useful", [item.get("text") for item in sent])
        self.assertEqual(invoke_response(sent)["status"], 200)

    async def test_feedback_fetch_returns_input_dialog(self):
        sent = await dispatch(self.app, {
            "type": "invoke", "name": "message/fetchTask",
            "value": {"commandId": "feedback", "context": "message"},
        })
        response = invoke_response(sent)
        self.assertEqual(response["status"], 200)
        task = response["body"]["task"]
        self.assertEqual(task["type"], "continue")
        card = task["value"]["card"]["content"]
        self.assertEqual(card["body"][1]["id"], "feedbackText")
        self.assertEqual(card["actions"][0]["type"], "Action.Submit")

    async def test_unknown_text_returns_stable_help(self):
        sent = await dispatch(self.app, {"text": "unknown"})
        self.assertRegex(sent[0]["text"], r"label.*sensitivity.*feedback.*citation")
        self.assertNotIn("AI bot", sent[0]["text"])
